function unquoteIdent(raw: string): string {
  const s = raw.trim();
  if (
    (s.startsWith('"') && s.endsWith('"')) ||
    (s.startsWith('`') && s.endsWith('`')) ||
    (s.startsWith('[') && s.endsWith(']'))
  ) {
    return s.slice(1, -1).replace(/""/g, '"').replace(/``/g, '`');
  }
  return s;
}

function parseQualifiedName(
  raw: string,
  defaultSchema = 'public',
): { schema: string; name: string } {
  const parts: string[] = [];
  let cur = '';
  let quote: string | null = null;
  for (let i = 0; i < raw.length; i += 1) {
    const ch = raw[i];
    if (quote) {
      cur += ch;
      if (ch === quote || (quote === '[' && ch === ']')) quote = null;
    } else if (ch === '"' || ch === '`' || ch === '[') {
      quote = ch;
      cur += ch;
    } else if (ch === '.') {
      parts.push(unquoteIdent(cur));
      cur = '';
    } else {
      cur += ch;
    }
  }
  if (cur.trim()) parts.push(unquoteIdent(cur));
  if (parts.length >= 2) {
    return { schema: parts[parts.length - 2], name: parts[parts.length - 1] };
  }
  return { schema: defaultSchema, name: parts[0] || '' };
}

function stripSqlComments(sql: string): string {
  let out = '';
  let i = 0;
  let inSingle = false;
  let inDouble = false;
  while (i < sql.length) {
    const ch = sql[i];
    const next = sql[i + 1];
    if (!inSingle && !inDouble) {
      if (ch === '-' && next === '-') {
        while (i < sql.length && sql[i] !== '\n') i += 1;
        continue;
      }
      if (ch === '/' && next === '*') {
        i += 2;
        while (i < sql.length && !(sql[i] === '*' && sql[i + 1] === '/')) {
          i += 1;
        }
        i += 2;
        out += ' ';
        continue;
      }
    }
    if (ch === "'" && !inDouble) {
      inSingle = !inSingle;
    } else if (ch === '"' && !inSingle) {
      inDouble = !inDouble;
    }
    out += ch;
    i += 1;
  }
  return out;
}

function splitTopLevel(input: string, sep: string): string[] {
  const parts: string[] = [];
  let cur = '';
  let depth = 0;
  let quote: string | null = null;
  for (let i = 0; i < input.length; i += 1) {
    const ch = input[i];
    if (quote) {
      cur += ch;
      if (ch === '\\' && i + 1 < input.length) {
        cur += input[i + 1];
        i += 1;
      } else if (ch === quote) {
        quote = null;
      }
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') {
      quote = ch;
      cur += ch;
      continue;
    }
    if (ch === '(' || ch === '[' || ch === '{') depth += 1;
    else if (ch === ')' || ch === ']' || ch === '}')
      depth = Math.max(0, depth - 1);
    if (ch === sep && depth === 0) {
      parts.push(cur);
      cur = '';
    } else {
      cur += ch;
    }
  }
  if (cur.trim()) parts.push(cur);
  return parts;
}

function extractMatchingParens(
  text: string,
  openIdx: number,
): { content: string; endIdx: number } | null {
  if (text[openIdx] !== '(') return null;
  let depth = 0;
  let quote: string | null = null;
  for (let i = openIdx; i < text.length; i += 1) {
    const ch = text[i];
    if (quote) {
      if (ch === '\\') {
        i += 1;
      } else if (ch === quote) {
        quote = null;
      }
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') {
      quote = ch;
      continue;
    }
    if (ch === '(') depth += 1;
    else if (ch === ')') {
      depth -= 1;
      if (depth === 0) {
        return { content: text.slice(openIdx + 1, i), endIdx: i };
      }
    }
  }
  return null;
}

export function parseSqlDdlToEr(sqlText: string): ErParseResult {
  const cleaned = stripSqlComments(sqlText);
  const statements = splitTopLevel(cleaned, ';')
    .map((s) => s.trim())
    .filter(Boolean);

  const tables: DataDbTableSchema[] = [];
  const tableMap = new Map<string, DataDbTableSchema>();
  const customTypes: DataDbCustomType[] = [];
  const warnings: string[] = [];

  const getOrLookupTable = (schema: string, name: string) =>
    tableMap.get(makeErTableId(schema, name).toLowerCase()) ??
    tables.find((t) => t.name.toLowerCase() === name.toLowerCase());

  for (const stmt of statements) {
    // 1. CREATE TYPE ... AS ENUM (...)
    const enumMatch = stmt.match(
      /^CREATE\s+TYPE\s+([^\s(]+)\s+AS\s+ENUM\s*\(([\s\S]+)\)$/i,
    );
    if (enumMatch) {
      const qn = parseQualifiedName(enumMatch[1]);
      const vals = splitTopLevel(enumMatch[2], ',')
        .map((v) => v.trim().replace(/^'|'$/g, '').replace(/''/g, "'"))
        .filter(Boolean);
      customTypes.push({
        name: qn.name,
        schema: qn.schema,
        kind: 'enum',
        values: vals,
        fields: [],
      });
      continue;
    }

    // 2. CREATE TABLE ... (...)
    const createTableMatch = stmt.match(
      /^CREATE\s+(?:TEMP(?:ORARY)?\s+|UNLOGGED\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([^\s(]+)/i,
    );
    if (createTableMatch) {
      const qn = parseQualifiedName(createTableMatch[1]);
      const openIdx = stmt.indexOf('(', createTableMatch[0].length);
      const body = openIdx >= 0 ? extractMatchingParens(stmt, openIdx) : null;
      if (!body) {
        warnings.push(`跳过无法提取表体括号的语句：${qn.name}`);
        continue;
      }

      const columns: DataColumnInfo[] = [];
      const primaryKeys: string[] = [];
      const foreignKeys: DataDbForeignKey[] = [];
      const indexes: DataDbIndexInfo[] = [];

      const items = splitTopLevel(body.content, ',')
        .map((s) => s.trim())
        .filter(Boolean);

      for (const item of items) {
        // Table-level PRIMARY KEY
        const tblPk = item.match(
          /^(?:CONSTRAINT\s+[^\s]+\s+)?PRIMARY\s+KEY\s*\(([^)]+)\)/i,
        );
        if (tblPk) {
          for (const c of splitTopLevel(tblPk[1], ',')) {
            const cn = unquoteIdent(c);
            if (cn && !primaryKeys.includes(cn)) primaryKeys.push(cn);
          }
          continue;
        }

        // Table-level FOREIGN KEY
        const tblFk = item.match(
          /^(?:CONSTRAINT\s+([^\s]+)\s+)?FOREIGN\s+KEY\s*\(([^)]+)\)\s*REFERENCES\s+([^\s(]+)\s*\(([^)]+)\)([\s\S]*)$/i,
        );
        if (tblFk) {
          const cname = tblFk[1] ? unquoteIdent(tblFk[1]) : null;
          const srcCols = splitTopLevel(tblFk[2], ',').map(unquoteIdent);
          const refQn = parseQualifiedName(tblFk[3], qn.schema);
          const refCols = splitTopLevel(tblFk[4], ',').map(unquoteIdent);
          const tail = tblFk[5] || '';
          const onUpd = tail.match(
            /ON\s+UPDATE\s+(NO\s+ACTION|RESTRICT|CASCADE|SET\s+NULL|SET\s+DEFAULT)/i,
          )?.[1];
          const onDel = tail.match(
            /ON\s+DELETE\s+(NO\s+ACTION|RESTRICT|CASCADE|SET\s+NULL|SET\s+DEFAULT)/i,
          )?.[1];
          srcCols.forEach((sc, idx) => {
            const rc = refCols[idx] ?? refCols[0];
            if (sc && rc) {
              foreignKeys.push({
                column: sc,
                refSchema: refQn.schema,
                refTable: refQn.name,
                refColumn: rc,
                constraintName: cname,
                onUpdate: onUpd ? onUpd.toUpperCase() : 'NO ACTION',
                onDelete: onDel ? onDel.toUpperCase() : 'NO ACTION',
              });
            }
          });
          continue;
        }

        // Table-level UNIQUE
        const tblUniq = item.match(
          /^(?:CONSTRAINT\s+([^\s]+)\s+)?UNIQUE\s*(?:KEY|INDEX)?\s*(?:[^\s(]+\s*)?\(([^)]+)\)/i,
        );
        if (tblUniq) {
          const uCols = splitTopLevel(tblUniq[2], ',').map(unquoteIdent);
          indexes.push({
            name: tblUniq[1]
              ? unquoteIdent(tblUniq[1])
              : `uq_${qn.name}_${uCols.join('_')}`,
            columns: uCols,
            unique: true,
            primary: false,
          });
          continue;
        }

        // Skip CHECK / EXCLUDE / KEY-only table constraints
        if (/^(?:CONSTRAINT\s+[^\s]+\s+)?(?:CHECK|EXCLUDE)\b/i.test(item)) {
          continue;
        }
        const mysqlKey = item.match(
          /^(?:INDEX|KEY)\s+([^\s(]+)\s*\(([^)]+)\)/i,
        );
        if (mysqlKey) {
          indexes.push({
            name: unquoteIdent(mysqlKey[1]),
            columns: splitTopLevel(mysqlKey[2], ',').map(unquoteIdent),
            unique: false,
            primary: false,
          });
          continue;
        }

        // Column definition: <colName> <dataType...> [constraints...]
        const colHead = item.match(
          /^("(?:""|[^"])*"|`(?:``|[^`])*`|\[[^\]]+\]|[^\s,()]+)\s+([\s\S]+)$/,
        );
        if (!colHead) continue;
        const colName = unquoteIdent(colHead[1]);
        const rest = colHead[2].trim();

        // Extract data type before constraint keywords
        const kwIdx = rest.search(
          /\b(?:NOT\s+NULL|NULL|PRIMARY\s+KEY|UNIQUE|DEFAULT|REFERENCES|CHECK|GENERATED|AUTO_INCREMENT|COLLATE|COMMENT)\b/i,
        );
        const dataType =
          (kwIdx >= 0 ? rest.slice(0, kwIdx) : rest).trim() || 'text';
        const constraintsPart = kwIdx >= 0 ? rest.slice(kwIdx) : '';

        const isPk = /\bPRIMARY\s+KEY\b/i.test(constraintsPart);
        const isNotNull = /\bNOT\s+NULL\b/i.test(constraintsPart) || isPk;
        const isUnique = /\bUNIQUE\b/i.test(constraintsPart);
        const defMatch = constraintsPart.match(
          /\bDEFAULT\s+('(?:''|[^'])*'|\([^)]*\)|[^\s,]+)/i,
        );
        const commentMatch = constraintsPart.match(
          /\bCOMMENT\s+'((?:''|[^'])*)'/i,
        );
        const inlineRef = constraintsPart.match(
          /\bREFERENCES\s+([^\s(]+)\s*\(([^)]+)\)/i,
        );

        if (isPk && !primaryKeys.includes(colName)) {
          primaryKeys.push(colName);
        }
        if (inlineRef) {
          const refQn = parseQualifiedName(inlineRef[1], qn.schema);
          const refCol = unquoteIdent(inlineRef[2]);
          if (refCol) {
            foreignKeys.push({
              column: colName,
              refSchema: refQn.schema,
              refTable: refQn.name,
              refColumn: refCol,
              onUpdate: 'NO ACTION',
              onDelete: 'NO ACTION',
            });
          }
        }

        columns.push({
          name: colName,
          dataType,
          nullable: !isNotNull,
          isPrimaryKey: isPk,
          isUnique,
          defaultValue: defMatch ? defMatch[1] : null,
          comment: commentMatch ? commentMatch[1].replace(/''/g, "'") : null,
        });
      }

      // Sync isPrimaryKey flag from table-level PK
      const pkSet = new Set(primaryKeys.map((p) => p.toLowerCase()));
      for (const c of columns) {
        if (pkSet.has(c.name.toLowerCase())) {
          c.isPrimaryKey = true;
          c.nullable = false;
        }
      }

      const tblSchema: DataDbTableSchema = {
        name: qn.name,
        schema: qn.schema,
        tableType: 'table',
        columns,
        primaryKeys,
        foreignKeys,
        indexes,
      };
      tables.push(tblSchema);
      tableMap.set(makeErTableId(qn.schema, qn.name).toLowerCase(), tblSchema);
      continue;
    }

    // 3. ALTER TABLE ... ADD FOREIGN KEY ...
    const alterFk = stmt.match(
      /^ALTER\s+TABLE\s+(?:ONLY\s+)?([^\s]+)\s+ADD\s+(?:CONSTRAINT\s+([^\s]+)\s+)?FOREIGN\s+KEY\s*\(([^)]+)\)\s*REFERENCES\s+([^\s(]+)\s*\(([^)]+)\)([\s\S]*)$/i,
    );
    if (alterFk) {
      const srcQn = parseQualifiedName(alterFk[1]);
      const srcTbl = getOrLookupTable(srcQn.schema, srcQn.name);
      if (srcTbl) {
        const cname = alterFk[2] ? unquoteIdent(alterFk[2]) : null;
        const srcCols = splitTopLevel(alterFk[3], ',').map(unquoteIdent);
        const refQn = parseQualifiedName(alterFk[4], srcQn.schema);
        const refCols = splitTopLevel(alterFk[5], ',').map(unquoteIdent);
        const tail = alterFk[6] || '';
        const onUpd = tail.match(
          /ON\s+UPDATE\s+(NO\s+ACTION|RESTRICT|CASCADE|SET\s+NULL|SET\s+DEFAULT)/i,
        )?.[1];
        const onDel = tail.match(
          /ON\s+DELETE\s+(NO\s+ACTION|RESTRICT|CASCADE|SET\s+NULL|SET\s+DEFAULT)/i,
        )?.[1];
        srcTbl.foreignKeys = srcTbl.foreignKeys ?? [];
        srcCols.forEach((sc, idx) => {
          const rc = refCols[idx] ?? refCols[0];
          if (sc && rc) {
            srcTbl.foreignKeys!.push({
              column: sc,
              refSchema: refQn.schema,
              refTable: refQn.name,
              refColumn: rc,
              constraintName: cname,
              onUpdate: onUpd ? onUpd.toUpperCase() : 'NO ACTION',
              onDelete: onDel ? onDel.toUpperCase() : 'NO ACTION',
            });
          }
        });
      }
      continue;
    }

    // 4. CREATE [UNIQUE] INDEX ... ON table (cols)
    const idxMatch = stmt.match(
      /^CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([^\s]+)\s+ON\s+([^\s(]+)\s*(?:USING\s+\w+\s*)?\(([^)]+)\)/i,
    );
    if (idxMatch) {
      const isUnique = Boolean(idxMatch[1]);
      const ixName = unquoteIdent(idxMatch[2]);
      const tQn = parseQualifiedName(idxMatch[3]);
      const tbl = getOrLookupTable(tQn.schema, tQn.name);
      if (tbl) {
        tbl.indexes = tbl.indexes ?? [];
        tbl.indexes.push({
          name: ixName,
          columns: splitTopLevel(idxMatch[4], ',').map((c) =>
            unquoteIdent(
              c.replace(/\s+(?:ASC|DESC|NULLS\s+FIRST|NULLS\s+LAST)\b/gi, ''),
            ),
          ),
          unique: isUnique,
          primary: false,
          definition: stmt,
        });
      }
      continue;
    }

    // 5. COMMENT ON TABLE / COLUMN
    const tblComment = stmt.match(
      /^COMMENT\s+ON\s+TABLE\s+([^\s]+)\s+IS\s+'((?:''|[^'])*)'$/i,
    );
    if (tblComment) {
      const qn = parseQualifiedName(tblComment[1]);
      const tbl = getOrLookupTable(qn.schema, qn.name);
      if (tbl) tbl.comment = tblComment[2].replace(/''/g, "'");
      continue;
    }
    const colComment = stmt.match(
      /^COMMENT\s+ON\s+COLUMN\s+([^\s]+)\s+IS\s+'((?:''|[^'])*)'$/i,
    );
    if (colComment) {
      const parts = colComment[1].split('.').map(unquoteIdent);
      if (parts.length >= 2) {
        const colName = parts[parts.length - 1];
        const tblName = parts[parts.length - 2];
        const schName = parts.length >= 3 ? parts[parts.length - 3] : 'public';
        const tbl = getOrLookupTable(schName, tblName);
        const col = tbl?.columns.find(
          (c) => c.name.toLowerCase() === colName.toLowerCase(),
        );
        if (col) col.comment = colComment[2].replace(/''/g, "'");
      }
    }
  }

  return { format: 'sql', tables, customTypes, warnings };
}

export function parseDbmlToEr(dbmlText: string): ErParseResult {
  // Strip // line comments
  const cleaned = dbmlText
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/\/\/[^\n]*/g, '');

  const tables: DataDbTableSchema[] = [];
  const tableMap = new Map<string, DataDbTableSchema>();
  const customTypes: DataDbCustomType[] = [];
  const warnings: string[] = [];

  // 1. Parse Enum blocks
  const enumRe = /\bEnum\s+([^\s{]+)\s*\{([^}]*)\}/gi;
  let em: RegExpExecArray | null;
  while ((em = enumRe.exec(cleaned)) !== null) {
    const qn = parseQualifiedName(em[1]);
    const vals = em[2]
      .split(/\r?\n/)
      .map((l) =>
        l
          .trim()
          .replace(/\s*\[.*\]$/, '')
          .trim(),
      )
      .filter(Boolean)
      .map(unquoteIdent);
    customTypes.push({
      name: qn.name,
      schema: qn.schema,
      kind: 'enum',
      values: vals,
      fields: [],
    });
  }

  // 2. Parse Table blocks (with nested indexes { ... } support)
  const tableStartRe = /\bTable\s+([^\s{]+)(?:\s+as\s+[^\s{]+)?\s*\{/gi;
  let tm: RegExpExecArray | null;
  while ((tm = tableStartRe.exec(cleaned)) !== null) {
    const qn = parseQualifiedName(tm[1]);
    const openIdx = tm.index + tm[0].length - 1;
    let depth = 0;
    let closeIdx = -1;
    for (let i = openIdx; i < cleaned.length; i += 1) {
      if (cleaned[i] === '{') depth += 1;
      else if (cleaned[i] === '}') {
        depth -= 1;
        if (depth === 0) {
          closeIdx = i;
          break;
        }
      }
    }
    if (closeIdx < 0) continue;
    const body = cleaned.slice(openIdx + 1, closeIdx);
    const columns: DataColumnInfo[] = [];
    const primaryKeys: string[] = [];
    const foreignKeys: DataDbForeignKey[] = [];
    const indexes: DataDbIndexInfo[] = [];
    let tableNote: string | null = null;

    // Extract indexes { ... } block first
    const bodyNoIndexes = body.replace(
      /\bindexes\s*\{([^}]*)\}/gi,
      (_all, idxBlock: string) => {
        for (const rawLine of idxBlock.split(/\r?\n/)) {
          const line = rawLine.trim();
          if (!line) continue;
          const m = line.match(/^(\([^)]+\)|[^\s[]+)(?:\s*\[([^\]]*)\])?/);
          if (!m) continue;
          const colSpec = m[1].replace(/^\(|\)$/g, '');
          const cols = splitTopLevel(colSpec, ',').map(unquoteIdent);
          const attrs = m[2] || '';
          const isPk = /\bpk\b/i.test(attrs);
          const isUniq = /\bunique\b/i.test(attrs);
          const nameM = attrs.match(/name:\s*['"]([^'"]+)['"]/i);
          if (isPk) {
            for (const c of cols) {
              if (!primaryKeys.includes(c)) primaryKeys.push(c);
            }
          } else {
            indexes.push({
              name: nameM?.[1] || `idx_${qn.name}_${cols.join('_')}`,
              columns: cols,
              unique: isUniq,
              primary: false,
            });
          }
        }
        return '';
      },
    );

    for (const rawLine of bodyNoIndexes.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line) continue;
      const noteLine = line.match(/^Note\s*:\s*['"]([^'"]*)['"]/i);
      if (noteLine) {
        tableNote = noteLine[1];
        continue;
      }
      const colM = line.match(
        /^("(?:[^"])*"|`(?:[^`])*`|[^\s]+)\s+("(?:[^"])*"|[^\s[]+(?:\([^)]*\))?)(?:\s*\[([^\]]*)\])?/,
      );
      if (!colM) continue;
      const colName = unquoteIdent(colM[1]);
      const colType = unquoteIdent(colM[2]);
      const attrs = colM[3] || '';
      const isPk = /\b(?:pk|primary\s+key)\b/i.test(attrs);
      const isNotNull = /\bnot\s+null\b/i.test(attrs) || isPk;
      const isUnique = /\bunique\b/i.test(attrs);
      const noteM = attrs.match(/note:\s*['"]([^'"]*)['"]/i);
      const defM = attrs.match(/default:\s*(`[^`]*`|'[^']*'|[^\s,\]]+)/i);
      const refM = attrs.match(/ref:\s*[<>-]+\s*([^\s,\]]+)/i);

      if (isPk && !primaryKeys.includes(colName)) primaryKeys.push(colName);
      if (refM) {
        const refParts = refM[1].split('.').map(unquoteIdent);
        if (refParts.length >= 2) {
          const refCol = refParts[refParts.length - 1];
          const refTbl = refParts[refParts.length - 2];
          const refSch =
            refParts.length >= 3 ? refParts[refParts.length - 3] : qn.schema;
          foreignKeys.push({
            column: colName,
            refSchema: refSch,
            refTable: refTbl,
            refColumn: refCol,
            onUpdate: 'NO ACTION',
            onDelete: 'NO ACTION',
          });
        }
      }

      columns.push({
        name: colName,
        dataType: colType,
        nullable: !isNotNull,
        isPrimaryKey: isPk,
        isUnique,
        defaultValue: defM ? defM[1].replace(/^`|`$/g, '') : null,
        comment: noteM ? noteM[1] : null,
      });
    }

    const pkSet = new Set(primaryKeys.map((p) => p.toLowerCase()));
    for (const c of columns) {
      if (pkSet.has(c.name.toLowerCase())) {
        c.isPrimaryKey = true;
        c.nullable = false;
      }
    }

    const tblObj: DataDbTableSchema = {
      name: qn.name,
      schema: qn.schema,
      tableType: 'table',
      comment: tableNote,
      columns,
      primaryKeys,
      foreignKeys,
      indexes,
    };
    tables.push(tblObj);
    tableMap.set(makeErTableId(qn.schema, qn.name).toLowerCase(), tblObj);
  }

  // 3. Standalone Ref statements
  const refRe =
    /\bRef(?:\s+([^\s:]+))?\s*:\s*([^\s<>-]+)\s*(<>|[<>-])\s*([^\s[\n]+)(?:\s*\[([^\]]*)\])?/gi;
  let rm: RegExpExecArray | null;
  while ((rm = refRe.exec(cleaned)) !== null) {
    const cname = rm[1] ? unquoteIdent(rm[1]) : null;
    const leftParts = rm[2].split('.').map(unquoteIdent);
    const op = rm[3];
    const rightParts = rm[4].split('.').map(unquoteIdent);
    const opts = rm[5] || '';
    if (leftParts.length < 2 || rightParts.length < 2) continue;

    const flip = op === '<';
    const srcP = flip ? rightParts : leftParts;
    const tgtP = flip ? leftParts : rightParts;

    const srcCol = srcP[srcP.length - 1];
    const srcTblName = srcP[srcP.length - 2];
    const srcSch = srcP.length >= 3 ? srcP[srcP.length - 3] : 'public';
    const tgtCol = tgtP[tgtP.length - 1];
    const tgtTblName = tgtP[tgtP.length - 2];
    const tgtSch = tgtP.length >= 3 ? tgtP[tgtP.length - 3] : 'public';

    const srcTbl =
      tableMap.get(makeErTableId(srcSch, srcTblName).toLowerCase()) ??
      tables.find((t) => t.name.toLowerCase() === srcTblName.toLowerCase());
    if (srcTbl) {
      const updM = opts.match(/update:\s*([a-z\s]+)/i);
      const delM = opts.match(/delete:\s*([a-z\s]+)/i);
      srcTbl.foreignKeys = srcTbl.foreignKeys ?? [];
      srcTbl.foreignKeys.push({
        column: srcCol,
        refSchema: tgtSch,
        refTable: tgtTblName,
        refColumn: tgtCol,
        constraintName: cname,
        onUpdate: updM ? updM[1].trim().toUpperCase() : 'NO ACTION',
        onDelete: delM ? delM[1].trim().toUpperCase() : 'NO ACTION',
      });
    }
  }

  return { format: 'dbml', tables, customTypes, warnings };
}

export function parseErImportText(rawText: string): ErParseResult {
  const trimmed = rawText.trim();
  if (!trimmed) {
    return {
      format: 'sql',
      tables: [],
      customTypes: [],
      warnings: ['输入内容为空。'],
    };
  }

  // 1. JSON snapshot
  if (trimmed.startsWith('{')) {
    try {
      const parsed = JSON.parse(trimmed) as Partial<SeamindErJsonSnapshot>;
      if (parsed.format === 'seamind-er-v1' && Array.isArray(parsed.tables)) {
        return {
          format: 'json',
          title: parsed.title,
          tables: parsed.tables,
          customTypes: Array.isArray(parsed.customTypes)
            ? parsed.customTypes
            : [],
          overlayPatch: parsed.overlay,
          warnings: [],
        };
      }
    } catch {
      // Fall through to text parsers
    }
  }

  // 2. DBML heuristic
  if (
    /^\s*(?:Table|Enum|Ref|Project|TableGroup)\s+/im.test(trimmed) &&
    !/\bCREATE\s+TABLE\b/i.test(trimmed)
  ) {
    return parseDbmlToEr(trimmed);
  }

  // 3. SQL DDL default
  return parseSqlDdlToEr(trimmed);
}
