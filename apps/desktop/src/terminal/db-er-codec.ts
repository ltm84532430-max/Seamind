export type ErExportSqlDialect = 'postgres' | 'mysql' | 'sqlite';

function qIdent(name: string, dialect: ErExportSqlDialect): string {
  if (dialect === 'mysql') return `\`${name.replace(/`/g, '``')}\``;
  return `"${name.replace(/"/g, '""')}"`;
}

function qTableRef(table: ErTable, dialect: ErExportSqlDialect): string {
  if (dialect === 'sqlite') return qIdent(table.name, dialect);
  if (
    table.schema &&
    table.schema !== 'main' &&
    table.schema !== 'default' &&
    !(dialect === 'postgres' && table.schema === 'public')
  ) {
    return `${qIdent(table.schema, dialect)}.${qIdent(table.name, dialect)}`;
  }
  return qIdent(table.name, dialect);
}

function escapeSqlLiteral(val: string): string {
  return `'${val.replace(/'/g, "''")}'`;
}

function escapeXml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

function mapTypeForDialect(
  rawType: string,
  dialect: ErExportSqlDialect,
): string {
  const clean = (rawType || 'text').trim();
  const low = clean.toLowerCase();
  if (dialect === 'postgres') return clean;
  if (dialect === 'mysql') {
    if (low === 'text' || low === 'character varying') return 'VARCHAR(255)';
    if (low === 'boolean' || low === 'bool') return 'TINYINT(1)';
    if (low.startsWith('timestamp with time zone') || low === 'timestamptz') {
      return 'DATETIME';
    }
    if (low === 'jsonb') return 'JSON';
    if (low === 'bytea') return 'BLOB';
    if (low === 'uuid') return 'CHAR(36)';
    if (low === 'serial') return 'INT AUTO_INCREMENT';
    if (low === 'bigserial') return 'BIGINT AUTO_INCREMENT';
    return clean;
  }
  // sqlite
  if (/\b(?:int|serial)\b/i.test(low)) return 'INTEGER';
  if (/\b(?:numeric|decimal|real|float|double)\b/i.test(low)) return 'REAL';
  if (/\b(?:bytea|blob|binary)\b/i.test(low)) return 'BLOB';
  return 'TEXT';
}

/* --------------------------------------------------------------------------
   1. Export to SQL DDL (PostgreSQL / MySQL / SQLite)
   -------------------------------------------------------------------------- */

export function exportErToSql(
  diagram: ErDiagramState,
  dialect: ErExportSqlDialect = 'postgres',
  options?: { includeLogicalRelations?: boolean },
): string {
  const includeLogical = options?.includeLogicalRelations ?? true;
  const lines: string[] = [
    `-- Generated by Seamind Database ER Studio`,
    `-- Source: ${diagram.title}`,
    `-- Dialect: ${dialect.toUpperCase()}`,
    '',
  ];

  const dbTables = diagram.tables.filter(
    (t) => t.sourceKind !== 'local-file' && !t.missingInLive,
  );
  const tableById = new Map(dbTables.map((t) => [t.id, t]));

  // Non-public schemas (Postgres)
  if (dialect === 'postgres') {
    const schemas = Array.from(
      new Set(
        dbTables
          .map((t) => t.schema)
          .filter(
            (s) => s && s !== 'public' && s !== 'main' && s !== 'default',
          ),
      ),
    );
    for (const sch of schemas) {
      lines.push(`CREATE SCHEMA IF NOT EXISTS ${qIdent(sch, dialect)};`);
    }
    if (schemas.length > 0) lines.push('');

    // Custom types
    for (const ct of diagram.customTypes) {
      const typeRef =
        ct.schema && ct.schema !== 'public'
          ? `${qIdent(ct.schema, dialect)}.${qIdent(ct.name, dialect)}`
          : qIdent(ct.name, dialect);
      if (ct.kind === 'enum' && ct.values.length > 0) {
        const vals = ct.values.map(escapeSqlLiteral).join(', ');
        lines.push(`CREATE TYPE ${typeRef} AS ENUM (${vals});`);
      } else if (ct.kind === 'composite' && ct.fields.length > 0) {
        const flds = ct.fields
          .map((f) => `  ${qIdent(f.name, dialect)} ${f.dataType}`)
          .join(',\n');
        lines.push(`CREATE TYPE ${typeRef} AS (\n${flds}\n);`);
      }
    }
    if (diagram.customTypes.length > 0) lines.push('');
  }

  const activeRels = diagram.relations.filter(
    (r) =>
      tableById.has(r.sourceTableId) &&
      tableById.has(r.targetTableId) &&
      (r.kind === 'physical' || (includeLogical && r.kind === 'logical')),
  );

  // CREATE TABLE blocks
  for (const tbl of dbTables) {
    const tRef = qTableRef(tbl, dialect);
    const bodyLines: string[] = [];

    for (const col of tbl.columns) {
      const parts = [
        `  ${qIdent(col.name, dialect)}`,
        mapTypeForDialect(col.dataType, dialect),
      ];
      if (!col.nullable) parts.push('NOT NULL');
      if (col.isUnique && !col.isPrimaryKey) parts.push('UNIQUE');
      if (col.defaultValue != null && col.defaultValue.trim() !== '') {
        parts.push(`DEFAULT ${col.defaultValue.trim()}`);
      }
      bodyLines.push(parts.join(' '));
    }

    if (tbl.primaryKeys.length > 0) {
      const pkCols = tbl.primaryKeys.map((c) => qIdent(c, dialect)).join(', ');
      bodyLines.push(`  PRIMARY KEY (${pkCols})`);
    }

    // Inline FKs for SQLite
    if (dialect === 'sqlite') {
      const tblFks = activeRels.filter((r) => r.sourceTableId === tbl.id);
      for (const rel of tblFks) {
        const tgt = tableById.get(rel.targetTableId);
        if (!tgt) continue;
        let fkLine = `  FOREIGN KEY (${qIdent(rel.sourceColumn, dialect)}) REFERENCES ${qTableRef(tgt, dialect)} (${qIdent(rel.targetColumn, dialect)})`;
        if (rel.onUpdate && rel.onUpdate !== 'NO ACTION') {
          fkLine += ` ON UPDATE ${rel.onUpdate}`;
        }
        if (rel.onDelete && rel.onDelete !== 'NO ACTION') {
          fkLine += ` ON DELETE ${rel.onDelete}`;
        }
        bodyLines.push(fkLine);
      }
    }

    lines.push(`CREATE TABLE ${tRef} (`);
    lines.push(bodyLines.join(',\n'));
    lines.push(');');

    // Indexes (non-primary)
    for (const ix of tbl.indexes) {
      if (ix.primary || ix.columns.length === 0) continue;
      const uKw = ix.unique ? 'UNIQUE ' : '';
      const ixCols = ix.columns.map((c) => qIdent(c, dialect)).join(', ');
      lines.push(
        `CREATE ${uKw}INDEX ${qIdent(ix.name, dialect)} ON ${tRef} (${ixCols});`,
      );
    }

    // Comments (PostgreSQL)
    if (dialect === 'postgres') {
      const tblNote = [tbl.alias, tbl.note, tbl.comment]
        .filter((s): s is string => Boolean(s && s.trim()))
        .join(' — ');
      if (tblNote) {
        lines.push(`COMMENT ON TABLE ${tRef} IS ${escapeSqlLiteral(tblNote)};`);
      }
      for (const col of tbl.columns) {
        const colNote = [col.note, col.comment]
          .filter((s): s is string => Boolean(s && s.trim()))
          .join(' — ');
        if (colNote) {
          lines.push(
            `COMMENT ON COLUMN ${tRef}.${qIdent(col.name, dialect)} IS ${escapeSqlLiteral(colNote)};`,
          );
        }
      }
    }
    lines.push('');
  }

  // Foreign key constraints (PG / MySQL)
  if (dialect !== 'sqlite' && activeRels.length > 0) {
    lines.push('-- Foreign Key & Logical Relationships');
    for (const rel of activeRels) {
      const src = tableById.get(rel.sourceTableId);
      const tgt = tableById.get(rel.targetTableId);
      if (!src || !tgt) continue;
      const cname =
        rel.constraintName || `fk_${src.name}_${rel.sourceColumn}_${tgt.name}`;
      let stmt = `ALTER TABLE ${qTableRef(src, dialect)} ADD CONSTRAINT ${qIdent(cname, dialect)} FOREIGN KEY (${qIdent(rel.sourceColumn, dialect)}) REFERENCES ${qTableRef(tgt, dialect)} (${qIdent(rel.targetColumn, dialect)})`;
      if (rel.onUpdate && rel.onUpdate !== 'NO ACTION') {
        stmt += ` ON UPDATE ${rel.onUpdate}`;
      }
      if (rel.onDelete && rel.onDelete !== 'NO ACTION') {
        stmt += ` ON DELETE ${rel.onDelete}`;
      }
      stmt += ';';
      if (rel.kind === 'logical') {
        lines.push(`-- [Logical Relation] ${rel.note || ''}`.trim());
      }
      lines.push(stmt);
    }
    lines.push('');
  }

  return lines.join('\n').trim() + '\n';
}

/* --------------------------------------------------------------------------
   2. Export to DBML (Database Markup Language)
   -------------------------------------------------------------------------- */

function dbmlIdent(name: string): string {
  return /^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name) ? name : `"${name}"`;
}

function dbmlTableRef(table: ErTable): string {
  if (
    table.schema &&
    table.schema !== 'public' &&
    table.schema !== 'main' &&
    table.schema !== 'default'
  ) {
    return `${dbmlIdent(table.schema)}.${dbmlIdent(table.name)}`;
  }
  return dbmlIdent(table.name);
}

function dbmlCardinalityOp(c: ErCardinality): string {
  switch (c) {
    case '1:1':
    case '0:1':
      return '-';
    case '1:N':
      return '<';
    case 'N:M':
      return '<>';
    default:
      return '>';
  }
}

export function exportErToDbml(diagram: ErDiagramState): string {
  const lines: string[] = [
    `// Generated by Seamind Database ER Studio`,
    `// Source: ${diagram.title}`,
    '',
  ];

  for (const ct of diagram.customTypes) {
    if (ct.kind !== 'enum' || ct.values.length === 0) continue;
    const ref =
      ct.schema && ct.schema !== 'public'
        ? `${dbmlIdent(ct.schema)}.${dbmlIdent(ct.name)}`
        : dbmlIdent(ct.name);
    lines.push(`Enum ${ref} {`);
    for (const v of ct.values) {
      lines.push(`  ${dbmlIdent(v)}`);
    }
    lines.push('}', '');
  }

  const dbTables = diagram.tables.filter(
    (t) => t.sourceKind !== 'local-file' && !t.missingInLive,
  );
  const tableById = new Map(dbTables.map((t) => [t.id, t]));

  for (const tbl of dbTables) {
    lines.push(`Table ${dbmlTableRef(tbl)} {`);
    for (const col of tbl.columns) {
      const attrs: string[] = [];
      if (col.isPrimaryKey) attrs.push('pk');
      if (!col.nullable) attrs.push('not null');
      if (col.isUnique && !col.isPrimaryKey) attrs.push('unique');
      if (col.defaultValue) {
        attrs.push(`default: \`${col.defaultValue.replace(/`/g, "'")}\``);
      }
      const noteText = [col.note, col.comment].filter(Boolean).join(' — ');
      if (noteText) {
        attrs.push(`note: '${noteText.replace(/'/g, "\\'")}'`);
      }
      const safeType = /\s/.test(col.dataType)
        ? `"${col.dataType.replace(/"/g, "'")}"`
        : col.dataType;
      const attrStr = attrs.length > 0 ? ` [${attrs.join(', ')}]` : '';
      lines.push(`  ${dbmlIdent(col.name)} ${safeType}${attrStr}`);
    }

    const nonPkIndexes = tbl.indexes.filter(
      (ix) => !ix.primary && ix.columns.length > 0,
    );
    if (nonPkIndexes.length > 0) {
      lines.push('');
      lines.push('  indexes {');
      for (const ix of nonPkIndexes) {
        const colExpr =
          ix.columns.length === 1
            ? dbmlIdent(ix.columns[0])
            : `(${ix.columns.map(dbmlIdent).join(', ')})`;
        const ixAttrs = [`name: '${ix.name.replace(/'/g, "\\'")}'`];
        if (ix.unique) ixAttrs.push('unique');
        lines.push(`    ${colExpr} [${ixAttrs.join(', ')}]`);
      }
      lines.push('  }');
    }

    const tNote = [tbl.alias, tbl.note, tbl.comment]
      .filter(Boolean)
      .join(' — ');
    if (tNote) {
      lines.push(`  Note: '${tNote.replace(/'/g, "\\'")}'`);
    }
    lines.push('}', '');
  }

  for (const rel of diagram.relations) {
    if (rel.kind === 'inferred') continue;
    const src = tableById.get(rel.sourceTableId);
    const tgt = tableById.get(rel.targetTableId);
    if (!src || !tgt) continue;
    const op = dbmlCardinalityOp(rel.cardinality);
    const opts: string[] = [];
    if (rel.onUpdate && rel.onUpdate !== 'NO ACTION') {
      opts.push(`update: ${rel.onUpdate.toLowerCase()}`);
    }
    if (rel.onDelete && rel.onDelete !== 'NO ACTION') {
      opts.push(`delete: ${rel.onDelete.toLowerCase()}`);
    }
    const optStr = opts.length > 0 ? ` [${opts.join(', ')}]` : '';
    lines.push(
      `Ref: ${dbmlTableRef(src)}.${dbmlIdent(rel.sourceColumn)} ${op} ${dbmlTableRef(tgt)}.${dbmlIdent(rel.targetColumn)}${optStr}`,
    );
  }

  if (diagram.subjectAreas.length > 0) {
    lines.push('');
    for (const area of diagram.subjectAreas) {
      const members = dbTables.filter(
        (t) =>
          t.x >= area.x - 10 &&
          t.x <= area.x + area.width + 10 &&
          t.y >= area.y - 10 &&
          t.y <= area.y + area.height + 10,
      );
      if (members.length === 0) continue;
      lines.push(`TableGroup ${dbmlIdent(area.name)} {`);
      for (const m of members) {
        lines.push(`  ${dbmlTableRef(m)}`);
      }
      lines.push('}', '');
    }
  }

  return lines.join('\n').trim() + '\n';
}

/* --------------------------------------------------------------------------
   3. Export to Mermaid erDiagram
   -------------------------------------------------------------------------- */

function mermaidId(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_]/g, '_');
  return /^[0-9]/.test(cleaned) ? `t_${cleaned}` : cleaned || 'table';
}

function mermaidType(raw: string): string {
  return (
    (raw || 'text')
      .trim()
      .replace(/\s+/g, '_')
      .replace(/[^a-zA-Z0-9_()[\]-]/g, '') || 'text'
  );
}

function mermaidCardinality(rel: ErRelation): string {
  const isDashed = rel.kind !== 'physical';
  const line = isDashed ? '..' : '--';
  switch (rel.cardinality) {
    case '1:1':
      return `||${line}||`;
    case '0:1':
      return `|o${line}||`;
    case '1:N':
      return `||${line}o{`;
    case 'N:M':
      return `}o${line}o{`;
    case '0:N':
      return `}o${line}||`;
    default:
      return `}|${line}||`;
  }
}

export function exportErToMermaid(diagram: ErDiagramState): string {
  const lines: string[] = ['erDiagram'];
  const tableById = new Map(diagram.tables.map((t) => [t.id, t]));
  const fkColsByTable = new Map<string, Set<string>>();

  for (const r of diagram.relations) {
    if (r.kind === 'inferred') continue;
    const set = fkColsByTable.get(r.sourceTableId) ?? new Set<string>();
    set.add(r.sourceColumn.toLowerCase());
    fkColsByTable.set(r.sourceTableId, set);
  }

  for (const tbl of diagram.tables) {
    if (tbl.missingInLive) continue;
    const mid = mermaidId(tbl.id);
    lines.push(`    ${mid} {`);
    const fkSet = fkColsByTable.get(tbl.id) ?? new Set<string>();
    for (const col of tbl.columns) {
      const keys: string[] = [];
      if (col.isPrimaryKey) keys.push('PK');
      if (fkSet.has(col.name.toLowerCase())) keys.push('FK');
      if (col.isUnique && !col.isPrimaryKey) keys.push('UK');
      const keyStr = keys.length > 0 ? ` ${keys.join(',')}` : '';
      const rawNote = (col.note || col.comment || '').replace(/"/g, "'").trim();
      const noteStr = rawNote ? ` "${rawNote.slice(0, 48)}"` : '';
      lines.push(
        `        ${mermaidType(col.dataType)} ${mermaidId(col.name)}${keyStr}${noteStr}`,
      );
    }
    lines.push('    }');
  }

  for (const rel of diagram.relations) {
    if (rel.kind === 'inferred') continue;
    const src = tableById.get(rel.sourceTableId);
    const tgt = tableById.get(rel.targetTableId);
    if (!src || !tgt) continue;
    const label = `${rel.sourceColumn} -> ${rel.targetColumn}`.replace(
      /"/g,
      "'",
    );
    lines.push(
      `    ${mermaidId(src.id)} ${mermaidCardinality(rel)} ${mermaidId(tgt.id)} : "${label}"`,
    );
  }

  return lines.join('\n') + '\n';
}

/* --------------------------------------------------------------------------
   4. Export to Seamind Knowledge Base Markdown Data Dictionary
   -------------------------------------------------------------------------- */

export function exportErToMarkdownDictionary(
  diagram: ErDiagramState,
  connection: DataLabDbConnection | null,
): string {
  const activeTables = diagram.tables.filter((t) => !t.missingInLive);
  const totalRows = activeTables.reduce(
    (sum, t) =>
      sum + (t.estimatedRows && t.estimatedRows > 0 ? t.estimatedRows : 0),
    0,
  );
  const totalBytes = activeTables.reduce(
    (sum, t) => sum + (t.totalBytes && t.totalBytes > 0 ? t.totalBytes : 0),
    0,
  );
  const schemas = Array.from(new Set(activeTables.map((t) => t.schema)));
  const activeRels = diagram.relations.filter((r) => r.kind !== 'inferred');
  const tableById = new Map(activeTables.map((t) => [t.id, t]));

  const lines: string[] = [
    `# 数据库研究字典：${diagram.title}`,
    '',
    `> 由 **Seamind Database ER Studio** 生成 · 引擎：\`${diagram.dbType.toUpperCase()}\` · Schema：${schemas.length} 个 · 表/视图：${activeTables.length} 张 · 关系：${activeRels.length} 条${totalRows > 0 ? ` · 估算总行数：${formatEstimatedRows(totalRows)}` : ''}${totalBytes > 0 ? ` · 总占用：${formatFileSizeCompact(totalBytes)}` : ''}`,
    '',
    '## 一、实体关系总览（Mermaid ER 图）',
    '',
    '```mermaid',
    exportErToMermaid(diagram).trim(),
    '```',
    '',
  ];

  if (diagram.notes.length > 0) {
    lines.push('## 二、研究口径与画布便签', '');
    for (const n of diagram.notes) {
      lines.push(`### ${n.title || '研究便签'}`, '', n.content || '（空）', '');
    }
  }

  if (diagram.issues.length > 0) {
    lines.push('## 三、结构与数据质量体检摘要', '');
    lines.push('| 级别 | 维度 | 问题 | 说明 |');
    lines.push('| --- | --- | --- | --- |');
    for (const iss of diagram.issues.slice(0, 40)) {
      const sev =
        iss.severity === 'error'
          ? '错误'
          : iss.severity === 'warning'
            ? '警告'
            : '提示';
      const cat = iss.category === 'data-quality' ? '实库质量' : '建模规范';
      lines.push(
        `| ${sev} | ${cat} | ${iss.title.replace(/\|/g, '\\|')} | ${iss.detail.replace(/\|/g, '\\|')} |`,
      );
    }
    lines.push('');
  }

  lines.push('## 四、逐表字段字典', '');
  for (const tbl of activeTables) {
    const titleSuffix = tbl.alias ? ` — ${tbl.alias}` : '';
    lines.push(`### \`${tbl.id}\`${titleSuffix}`, '');
    const metaParts = [
      `类型：\`${tbl.tableType}\``,
      tbl.estimatedRows != null
        ? `估算行数：${formatEstimatedRows(tbl.estimatedRows)}`
        : '',
      tbl.totalBytes != null
        ? `磁盘体积：${formatFileSizeCompact(tbl.totalBytes)}`
        : '',
      tbl.primaryKeys.length > 0
        ? `主键：\`${tbl.primaryKeys.join(', ')}\``
        : '主键：无',
    ].filter(Boolean);
    lines.push(`- ${metaParts.join(' · ')}`);
    if (tbl.note || tbl.comment) {
      lines.push(
        `- 说明：${[tbl.note, tbl.comment].filter(Boolean).join(' / ')}`,
      );
    }
    lines.push('');
    lines.push('| 字段 | 类型 | 约束 | 默认值 | 业务释义 / 注释 |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const col of tbl.columns) {
      const tags: string[] = [];
      if (col.isPrimaryKey) tags.push('PK');
      if (!col.nullable) tags.push('NOT NULL');
      if (col.isUnique && !col.isPrimaryKey) tags.push('UNIQUE');
      const note = [col.note, col.comment]
        .filter(Boolean)
        .join(' / ')
        .replace(/\|/g, '\\|');
      lines.push(
        `| \`${col.name}\` | \`${col.dataType}\` | ${tags.join(', ') || 'NULL'} | ${col.defaultValue ? `\`${col.defaultValue}\`` : '—'} | ${note || '—'} |`,
      );
    }
    lines.push('');
  }

  if (activeRels.length > 0) {
    lines.push('## 五、常用关联 JOIN 查询模板', '');
    for (const rel of activeRels.slice(0, 12)) {
      const src = tableById.get(rel.sourceTableId);
      const tgt = tableById.get(rel.targetTableId);
      if (!src || !tgt) continue;
      const { sql } = buildRelationJoinSql(rel, src, tgt, connection, 100);
      lines.push(
        `### ${src.id}.${rel.sourceColumn} → ${tgt.id}.${rel.targetColumn} (\`${rel.cardinality}\`)`,
        '',
        '```sql',
        sql,
        '```',
        '',
      );
    }
  }

  return lines.join('\n');
}

/* --------------------------------------------------------------------------
   5. Export to Pure-Vector Standalone SVG (Zero foreignObject -> Crisp PNG/SVG)
   -------------------------------------------------------------------------- */

function renderCrowsFootSvg(
  pt: { x: number; y: number },
  dir: 1 | -1,
  side: 'one' | 'many' | 'zero-one' | 'zero-many',
  stroke: string,
): string {
  const ux = dir; // points outward from table edge along the stub
  const x0 = pt.x;
  const y0 = pt.y;
  const x1 = x0 + ux * 12;
  const x2 = x0 + ux * 16;
  const els: string[] = [];

  if (side === 'one') {
    els.push(
      `<line x1="${x0 + ux * 7}" y1="${y0 - 6}" x2="${x0 + ux * 7}" y2="${y0 + 6}" stroke="${stroke}" stroke-width="1.6"/>`,
    );
    els.push(
      `<line x1="${x0 + ux * 12}" y1="${y0 - 6}" x2="${x0 + ux * 12}" y2="${y0 + 6}" stroke="${stroke}" stroke-width="1.6"/>`,
    );
  } else if (side === 'zero-one') {
    els.push(
      `<line x1="${x0 + ux * 7}" y1="${y0 - 6}" x2="${x0 + ux * 7}" y2="${y0 + 6}" stroke="${stroke}" stroke-width="1.6"/>`,
    );
    els.push(
      `<circle cx="${x2}" cy="${y0}" r="4" fill="#ffffff" stroke="${stroke}" stroke-width="1.5"/>`,
    );
  } else {
    // Crow's foot three prongs
    els.push(
      `<line x1="${x1}" y1="${y0}" x2="${x0 + ux * 2}" y2="${y0 - 7}" stroke="${stroke}" stroke-width="1.6"/>`,
    );
    els.push(
      `<line x1="${x1}" y1="${y0}" x2="${x0 + ux * 2}" y2="${y0 + 7}" stroke="${stroke}" stroke-width="1.6"/>`,
    );
    if (side === 'zero-many') {
      els.push(
        `<circle cx="${x2 + ux * 2}" cy="${y0}" r="3.8" fill="#ffffff" stroke="${stroke}" stroke-width="1.5"/>`,
      );
    } else {
      els.push(
        `<line x1="${x1 + ux * 2}" y1="${y0 - 6}" x2="${x1 + ux * 2}" y2="${y0 + 6}" stroke="${stroke}" stroke-width="1.6"/>`,
      );
    }
  }
  return els.join('');
}

export function cardinalityEnds(c: ErCardinality): {
  source: 'one' | 'many' | 'zero-one' | 'zero-many';
  target: 'one' | 'many' | 'zero-one' | 'zero-many';
} {
  switch (c) {
    case '1:1':
      return { source: 'one', target: 'one' };
    case '0:1':
      return { source: 'zero-one', target: 'one' };
    case '1:N':
      return { source: 'one', target: 'many' };
    case 'N:M':
      return { source: 'many', target: 'many' };
    case '0:N':
      return { source: 'zero-many', target: 'one' };
    default:
      return { source: 'many', target: 'one' };
  }
}

export function exportErToStandaloneSvg(
  diagram: ErDiagramState,
  palette: 'light' | 'dark' = 'light',
): string {
  const isDark = palette === 'dark';
  const bg = isDark ? '#161b22' : '#f7f8fa';
  const cardBg = isDark ? '#1e2530' : '#ffffff';
  const cardBorder = isDark ? '#323c4a' : '#d5dbe2';
  const ink = isDark ? '#e6edf3' : '#1f2428';
  const muted = isDark ? '#8b949e' : '#656e75';
  const edgePhys = isDark ? '#7aa892' : '#467b5e';
  const edgeLogic = isDark ? '#6ca6cd' : '#3b6e8c';

  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (const t of diagram.tables) {
    const h = estimateTableCardHeight(t, false);
    minX = Math.min(minX, t.x);
    minY = Math.min(minY, t.y);
    maxX = Math.max(maxX, t.x + (t.width || ER_CARD_WIDTH));
    maxY = Math.max(maxY, t.y + h);
  }
  for (const a of diagram.subjectAreas) {
    minX = Math.min(minX, a.x);
    minY = Math.min(minY, a.y);
    maxX = Math.max(maxX, a.x + a.width);
    maxY = Math.max(maxY, a.y + a.height);
  }
  for (const n of diagram.notes) {
    minX = Math.min(minX, n.x);
    minY = Math.min(minY, n.y);
    maxX = Math.max(maxX, n.x + n.width);
    maxY = Math.max(maxY, n.y + n.height);
  }
  if (!Number.isFinite(minX)) {
    minX = 0;
    minY = 0;
    maxX = 640;
    maxY = 400;
  }

  const pad = 48;
  const vbX = Math.floor(minX - pad);
  const vbY = Math.floor(minY - pad);
  const vbW = Math.ceil(maxX - minX + pad * 2);
  const vbH = Math.ceil(maxY - minY + pad * 2);

  const parts: string[] = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vbX} ${vbY} ${vbW} ${vbH}" width="${vbW}" height="${vbH}">`,
    `<rect x="${vbX}" y="${vbY}" width="${vbW}" height="${vbH}" fill="${bg}"/>`,
  ];

  // 1. Subject Areas
  for (const a of diagram.subjectAreas) {
    parts.push(
      `<g>`,
      `<rect x="${a.x}" y="${a.y}" width="${a.width}" height="${a.height}" rx="8" fill="${escapeXml(a.color)}" fill-opacity="0.07" stroke="${escapeXml(a.color)}" stroke-opacity="0.45" stroke-width="1.4" stroke-dasharray="6 4"/>`,
      `<text x="${a.x + 14}" y="${a.y + 24}" font-family="Inter, Microsoft YaHei UI, sans-serif" font-size="13" font-weight="700" fill="${escapeXml(a.color)}">${escapeXml(a.name)}</text>`,
      `</g>`,
    );
  }

  // 2. Relationships
  const tableById = new Map(diagram.tables.map((t) => [t.id, t]));
  const visibleRels = diagram.relations.filter(
    (r) => r.kind !== 'inferred' || diagram.showInferred,
  );
  for (const rel of visibleRels) {
    const src = tableById.get(rel.sourceTableId);
    const tgt = tableById.get(rel.targetTableId);
    if (!src || !tgt) continue;
    const edge = calcErEdgePath(
      src,
      rel.sourceColumn,
      tgt,
      rel.targetColumn,
      diagram.routing,
      false,
    );
    const stroke =
      rel.kind === 'physical'
        ? edgePhys
        : rel.kind === 'logical'
          ? edgeLogic
          : muted;
    const dash =
      rel.kind === 'physical'
        ? ''
        : rel.kind === 'logical'
          ? ' stroke-dasharray="6 4"'
          : ' stroke-dasharray="3 4" stroke-opacity="0.55"';
    const ends = cardinalityEnds(rel.cardinality);
    parts.push(
      `<g>`,
      `<path d="${edge.pathD}" fill="none" stroke="${stroke}" stroke-width="1.65"${dash}/>`,
      renderCrowsFootSvg(edge.sourcePoint, edge.sourceDir, ends.source, stroke),
      renderCrowsFootSvg(edge.targetPoint, edge.targetDir, ends.target, stroke),
      `</g>`,
    );
  }

  // 3. Table Cards
  for (const t of diagram.tables) {
    const w = t.width || ER_CARD_WIDTH;
    const h = estimateTableCardHeight(t, false);
    const hasSub = hasTableSubmeta(t);
    const subH = hasSub ? ER_SUBMETA_H : 0;
    const displayName = t.alias ? `${t.id} (${t.alias})` : t.id;

    parts.push(`<g>`);
    parts.push(
      `<rect x="${t.x}" y="${t.y}" width="${w}" height="${h}" rx="6" fill="${cardBg}" stroke="${cardBorder}" stroke-width="1.2"/>`,
    );
    parts.push(
      `<rect x="${t.x}" y="${t.y}" width="${w}" height="4" rx="2" fill="${escapeXml(t.color)}"/>`,
    );
    parts.push(
      `<line x1="${t.x}" y1="${t.y + ER_HEADER_H}" x2="${t.x + w}" y2="${t.y + ER_HEADER_H}" stroke="${cardBorder}" stroke-width="1"/>`,
    );
    parts.push(
      `<text x="${t.x + 12}" y="${t.y + 24}" font-family="Inter, Microsoft YaHei UI, sans-serif" font-size="12.5" font-weight="700" fill="${ink}">${escapeXml(displayName.slice(0, 32))}</text>`,
    );

    if (hasSub) {
      const subText = [
        t.estimatedRows != null ? formatEstimatedRows(t.estimatedRows) : '',
        t.totalBytes != null ? formatFileSizeCompact(t.totalBytes) : '',
        `${t.columns.length} 列`,
      ]
        .filter(Boolean)
        .join(' · ');
      parts.push(
        `<text x="${t.x + 12}" y="${t.y + ER_HEADER_H + 15}" font-family="JetBrains Mono, Consolas, monospace" font-size="10" fill="${muted}">${escapeXml(subText)}</text>`,
      );
      parts.push(
        `<line x1="${t.x}" y1="${t.y + ER_HEADER_H + subH}" x2="${t.x + w}" y2="${t.y + ER_HEADER_H + subH}" stroke="${cardBorder}" stroke-width="0.8"/>`,
      );
    }

    if (!t.collapsed) {
      t.columns.forEach((col, idx) => {
        const cy = t.y + ER_HEADER_H + subH + idx * ER_ROW_H + 17;
        const badge = col.isPrimaryKey ? 'PK ' : col.isUnique ? 'UK ' : '';
        parts.push(
          `<text x="${t.x + 12}" y="${cy}" font-family="JetBrains Mono, Consolas, monospace" font-size="11" font-weight="${col.isPrimaryKey ? '700' : '400'}" fill="${col.isPrimaryKey ? escapeXml(t.color) : ink}">${escapeXml((badge + col.name).slice(0, 22))}</text>`,
        );
        parts.push(
          `<text x="${t.x + w - 12}" y="${cy}" text-anchor="end" font-family="JetBrains Mono, Consolas, monospace" font-size="10.5" fill="${muted}">${escapeXml(col.dataType.slice(0, 18))}</text>`,
        );
      });
    }
    parts.push(`</g>`);
  }

  // 4. Canvas Notes
  for (const n of diagram.notes) {
    parts.push(
      `<g>`,
      `<rect x="${n.x}" y="${n.y}" width="${n.width}" height="${n.height}" rx="6" fill="${escapeXml(n.color)}" stroke="#b8a878" stroke-width="1"/>`,
      `<text x="${n.x + 12}" y="${n.y + 22}" font-family="Inter, Microsoft YaHei UI, sans-serif" font-size="12" font-weight="700" fill="#2c2a24">${escapeXml((n.title || '便签').slice(0, 28))}</text>`,
      `<text x="${n.x + 12}" y="${n.y + 42}" font-family="Inter, Microsoft YaHei UI, sans-serif" font-size="11" fill="#464236">${escapeXml((n.content || '').split('\n')[0].slice(0, 34))}</text>`,
      `</g>`,
    );
  }

  parts.push('</svg>');
  return parts.join('\n');
}

